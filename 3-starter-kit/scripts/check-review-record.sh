#!/bin/bash
# 리뷰 기록 칸 점검 — /done 증적 댓글을 올리기 «전에» 본문 파일로 돌린다 (done/단계상세.md §9 «기록 칸»)
# 여섯 칸(방식·리뷰어 수·시간·토큰·확정 건수·결함 위치)이 각각 «값 또는 미제공»으로 적혔는지 본다.
# 값이 없는 칸 = 종료 1. 파일을 못 읽으면 2(점검 불능 — 통과가 아니다).
# 쓰는 법: bash scripts/check-review-record.sh <본문파일>
f="$1"
if [ -z "$f" ] || [ ! -r "$f" ]; then echo "⛔ 점검 불능: 본문 파일을 못 읽음 ($f)"; exit 2; fi
miss=0
# 라벨 뒤 12자 안에, 칸 구분(· 또는 |)을 넘지 않고 «값»(숫자·단일·merge-review·대상·비계·해당 없음·미제공)이 있어야 칸이 찼다고 본다
# ⚠️구분을 · 와 | 로 안 쓴 서식(줄바꿈·쉼표만)에선 옆 칸 숫자를 값으로 읽을 수 있다 — 칸마다 줄을 나누거나 · 로 이어라
chk() {
  name="$1"; label="$2"; val="$3"
  if ! grep -aEq "($label)[^·|]{0,12}($val)" "$f"; then echo "⛔ 빈 칸: $name (값 또는 «미제공» 을 적어라 — 0 으로 적지 마라)"; miss=$((miss+1)); fi
}
chk "방식" "방식" "단일|merge-review|워크플로|미제공"
chk "리뷰어 수" "리뷰어" "[0-9]|한 ?명|미제공"
chk "시간" "소요|시간" "[0-9]|미제공"
chk "토큰" "토큰" "[0-9]|미제공"
chk "확정 건수" "확정|재현된 결함|결함 [0-9]" "[0-9]|없음|미제공"
chk "결함 위치" "결함 위치" "대상|비계|해당 없음|미제공"
if [ "$miss" -gt 0 ]; then echo "리뷰 기록 칸 $miss 개 비었다 — 채운 뒤 다시 돌려라"; exit 1; fi
echo "리뷰 기록 칸 6/6 OK"
exit 0
