#!/usr/bin/env bash
# check-append-only.py 의 회귀 테스트 — 「거짓 ⛔」와 「놓친 삭제」 둘 다 사고다.
# ★A 가 이 파일의 존재 이유다: 2026-09-10(#268) 에 «줄 앞머리를 고친» 정상 편집이 ⛔ 로 찍혔고,
#   사람이 그 ⛔ 를 안고 그대로 올렸다. 거짓 ⛔ 는 진짜 ⛔ 를 무력화한다.
# ★C 는 그 반대다: 옛 판은 `any(...)` 라 한 줄이 여러 줄의 짝 노릇을 해서, 닮은 두 줄 중
#   하나를 지워도 통과했다 — 이 도구가 막으려던 «남의 줄이 조용히 사라지는» 바로 그 사고다.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
TOOL="$HERE/check-append-only.py"
OK=0; FAIL=0

command -v python3 >/dev/null 2>&1 || {
  echo "⛔ python3 이 없다 — 이 시험은 python3 이 있어야 성립한다(«건너뜀»이 아니라 실패다)."
  echo "   CI 라면 그 잡의 이미지에 python3 를 깔아라(킷 self-tests = alpine: \`apk add python3\`)."
  exit 1; }

TMP="${TMPDIR:-/tmp}/cao.$$"; mkdir -p "$TMP" || { echo "⛔ 임시 폴더를 못 만든다: $TMP"; exit 1; }
trap 'rm -rf "$TMP"' EXIT
touch "$TMP/.w" 2>/dev/null || { echo "⛔ 임시 폴더에 못 쓴다 — 울타리 안에서는 여기서 돌리지 마라"; exit 1; }

run() { python3 "$TOOL" "$TMP/before.md" "$TMP/after.md" ${1:+--moved-to "$1"} > "$TMP/out" 2>&1; echo $?; }
ck() { # $1=설명 $2=기대 exit $3=실제 exit
  if [ "$2" = "$3" ]; then OK=$((OK+1))
  else FAIL=$((FAIL+1)); echo "  ⛔ $1"; echo "     기대 exit: $2 / 실제: $3"; sed 's/^/       /' "$TMP/out" | head -5; fi
}

echo "── A. ★줄 «앞머리»를 고친 정상 편집은 통과해야 한다 (거짓 ⛔ 금지)"
# ★실측 기준: #268 의 실제 편집(줄 앞머리의 오너 인용 → 요지)은 닮음 **0.925** 였다. 문턱 0.7 은 그 아래로 넉넉하다.
#   ⚠️단 «닮음»은 짧은 줄에서 크게 흔들린다 — 이 도구가 겨누는 것은 수백 자짜리 누적 줄이라 그 자리에서만 믿어라.
cat > "$TMP/before.md" <<'E'
2026-09-09 /fix — **«아니오가 나올 수 없는» 자리에서 반복 정지해 오너가 「일일이 승인해야 해서 너무 불편하다」고 지적했다.** 한 세션에서 정지 12회 중 4회가 도장찍기였다: 측정 결과를 카드에 기록할지 2회, 이미 고른 메시지를 보낼지, 카드를 닫을지. 판별 기준이 절 끝에 있어 목록이 먼저 읽힌 탓이다.
2026-09-08 /dev — 다른 줄이다
E
cat > "$TMP/after.md" <<'E'
2026-09-09 /fix — **«아니오가 나올 수 없는» 자리에서 반복 정지해 오너가 승인 요구가 너무 잦다고 지적했다.** 한 세션에서 정지 12회 중 4회가 도장찍기였다: 측정 결과를 카드에 기록할지 2회, 이미 고른 메시지를 보낼지, 카드를 닫을지. 판별 기준이 절 끝에 있어 목록이 먼저 읽힌 탓이다. [닫힘:이 커밋]
2026-09-08 /dev — 다른 줄이다
E
ck "A1 앞머리를 고쳐도 «사라짐»이 아니다" "0" "$(run)"

echo "── B. 뒤에 덧붙인 것(닫힘 표시)도 통과한다"
cat > "$TMP/before.md" <<'E'
2026-09-10 /card — 어떤 문제가 있었다
E
cat > "$TMP/after.md" <<'E'
2026-09-10 /card — 어떤 문제가 있었다 [닫힘:이 커밋]
E
ck "B1 덧붙임은 통과" "0" "$(run)"

echo "── C. ★한 줄이 여러 줄의 «짝» 노릇을 하면 안 된다 (하나에 하나 — 옛 판이 놓치던 자리)"
# 앞머리가 80자 넘게 겹치는 두 줄 중 «짧은 쪽»이 사라졌다. 옛 판은 `any(startswith)` 라
# 긴 쪽이 짧은 쪽의 짝 노릇까지 해서 exit 0 을 냈다 — 이 도구가 막으려던 바로 그 사고다.
cat > "$TMP/before.md" <<'E'
2026-09-10 /fix(#249) — 같은 날 같은 카드에서 나온 줄이라 앞부분이 길게 겹친다. 여기까지가 첫 80자를 훌쩍 넘는 공통 앞머리다.
2026-09-10 /fix(#249) — 같은 날 같은 카드에서 나온 줄이라 앞부분이 길게 겹친다. 여기까지가 첫 80자를 훌쩍 넘는 공통 앞머리다. 그리고 이 줄에는 뒤에 덧붙은 말이 더 있다.
E
cat > "$TMP/after.md" <<'E'
2026-09-10 /fix(#249) — 같은 날 같은 카드에서 나온 줄이라 앞부분이 길게 겹친다. 여기까지가 첫 80자를 훌쩍 넘는 공통 앞머리다. 그리고 이 줄에는 뒤에 덧붙은 말이 더 있다.
E
ck "C1 겹치는 두 줄 중 하나가 사라지면 exit 1" "1" "$(run)"

echo "── D. 통째로 사라진 줄은 잡는다"
cat > "$TMP/before.md" <<'E'
2026-09-10 /card — 남이 적은 줄
2026-09-09 /dev — 내 줄
E
cat > "$TMP/after.md" <<'E'
2026-09-09 /dev — 내 줄
E
ck "D1 남의 줄 삭제는 exit 1" "1" "$(run)"

echo "── E. 보관 파일로 «옮긴» 것은 통과한다"
cat > "$TMP/before.md" <<'E'
2026-09-01 /card — 옛 줄 [닫힘:구기록]
2026-09-09 /dev — 최근 줄
E
cat > "$TMP/after.md" <<'E'
2026-09-09 /dev — 최근 줄
E
cat > "$TMP/archive.md" <<'E'
2026-09-01 /card — 옛 줄 [닫힘:구기록]
E
ck "E1 보관으로 옮긴 줄은 통과" "0" "$(run "$TMP/archive.md")"

echo "── F. 날짜가 다르면 «닮음»으로 이어 붙이지 않는다"
cat > "$TMP/before.md" <<'E'
2026-09-10 /card — 아주 비슷한 문장을 가진 줄이다 여기까지 같다
E
cat > "$TMP/after.md" <<'E'
2026-09-08 /card — 아주 비슷한 문장을 가진 줄이다 여기까지 같다
E
ck "F1 날짜가 다르면 exit 1" "1" "$(run)"

echo "── G. ★보관하며 «글자까지 같은» 중복 줄이 접혀도 통과한다 (거짓 ⛔ 금지)"
# archive-friction.py 는 보관할 때 완전 동일 줄을 접는다. 검사기가 그걸 «사라짐»으로 읽으면
# 보관 작업 MR 이 통째로 막힌다 — 2026-09-16 배포처 #285 가 실측했고 킷에서 재현했다.
cat > "$TMP/before.md" <<'E'
2026-09-01 /dev — 같은 줄
2026-09-01 /dev — 같은 줄
2026-09-02 /fix — 다른 줄
E
cat > "$TMP/after.md" <<'E'
2026-09-01 /dev — 같은 줄
2026-09-02 /fix — 다른 줄
E
ck "G1 중복이 접혀도 exit 0" "0" "$(run)"

echo "── H. ★그 접기가 «진짜 삭제»를 가리면 안 된다 (G 의 반대 방향 — 이쪽이 더 위험하다)"
# 사라지는 줄은 남은 중복과 같은 날짜이고 앞 80자가 겹친다 = «여분이 짝 노릇을 할» 모양이다.
# 세 쪽 모두에서 접어야 여기서 잡힌다. 한쪽만 접으면 남은 여분이 이 줄의 짝이 되어 exit 0 이 된다.
cat > "$TMP/before.md" <<'E'
2026-09-01 /dev — 같은 줄이고 이 문장은 길어서 앞 80자가 겹친다 여기까지가 공통 앞머리다 계속 이어진다
2026-09-01 /dev — 같은 줄이고 이 문장은 길어서 앞 80자가 겹친다 여기까지가 공통 앞머리다 계속 이어진다
2026-09-01 /dev — 같은 줄이고 이 문장은 길어서 앞 80자가 겹친다 여기까지가 공통 앞머리다 그런데 뒤가 다르다
E
cat > "$TMP/after.md" <<'E'
2026-09-01 /dev — 같은 줄이고 이 문장은 길어서 앞 80자가 겹친다 여기까지가 공통 앞머리다 계속 이어진다
2026-09-01 /dev — 같은 줄이고 이 문장은 길어서 앞 80자가 겹친다 여기까지가 공통 앞머리다 계속 이어진다
E
ck "H1 중복이 있어도 진짜 삭제는 exit 1" "1" "$(run)"

echo "── I. ★H 와 같은 사고를 «짝짓기 ②»(앞 80자) 경로로도 한 번 — 두 경로가 따로 뚫린다"
# H 의 줄은 80자보다 짧아 ③(같은 날짜 + 닮음)으로 잡힌다. 앞 80자가 실제로 겹치는 긴 줄은
# ②(startswith)로 잡히는데, 접기가 한쪽만이면 «그 경로에서만» 삭제가 가려질 수 있다.
# 2026-09-16: 배포처 #285 는 반대로 ②만 덮고 ③이 비어 있었다 — 두 경로는 서로를 안 지켜 준다.
cat > "$TMP/before.md" <<'E'
2026-09-01 /dev — 이 줄은 앞머리가 아주 길어서 첫 80자를 확실히 넘긴다 그래서 짝짓기 ②(앞 80자로 시작하는지)가 걸리는 모양이 되고 여기까지가 두 줄의 공통 앞머리이며 이 뒤부터 갈린다 계속 이어진다
2026-09-01 /dev — 이 줄은 앞머리가 아주 길어서 첫 80자를 확실히 넘긴다 그래서 짝짓기 ②(앞 80자로 시작하는지)가 걸리는 모양이 되고 여기까지가 두 줄의 공통 앞머리이며 이 뒤부터 갈린다 계속 이어진다
2026-09-01 /dev — 이 줄은 앞머리가 아주 길어서 첫 80자를 확실히 넘긴다 그래서 짝짓기 ②(앞 80자로 시작하는지)가 걸리는 모양이 되고 여기까지가 두 줄의 공통 앞머리이며 이 뒤부터 갈린다 그런데 뒤가 다르다
E
cat > "$TMP/after.md" <<'E'
2026-09-01 /dev — 이 줄은 앞머리가 아주 길어서 첫 80자를 확실히 넘긴다 그래서 짝짓기 ②(앞 80자로 시작하는지)가 걸리는 모양이 되고 여기까지가 두 줄의 공통 앞머리이며 이 뒤부터 갈린다 계속 이어진다
2026-09-01 /dev — 이 줄은 앞머리가 아주 길어서 첫 80자를 확실히 넘긴다 그래서 짝짓기 ②(앞 80자로 시작하는지)가 걸리는 모양이 되고 여기까지가 두 줄의 공통 앞머리이며 이 뒤부터 갈린다 계속 이어진다
E
ck "I1 앞 80자 겹침 경로에서도 진짜 삭제는 exit 1" "1" "$(run)"

echo "────────  $OK OK / $FAIL FAIL"
[ "$FAIL" = 0 ] || exit 1
